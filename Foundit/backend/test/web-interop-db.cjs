// Runs against PostgreSQL in PGlite without connecting to or changing production data.
const assert = require('node:assert/strict');
const { pathToFileURL } = require('node:url');
const { resolve } = require('node:path');
const { WebInterop1793059200000 } = require('../dist/database/migrations/1793059200000-WebInterop');
const { Campus1793059201000 } = require('../dist/database/migrations/1793059201000-Campus');
const { LegacyCampus1793059202000 } = require('../dist/database/migrations/1793059202000-LegacyCampus');
const { CampusService } = require('../dist/campus/campus.service');
const { PointsService } = require('../dist/points/points.service');
async function main() {
  const library = process.env.PGLITE_MODULE || '@electric-sql/pglite';
  const { PGlite } = await import(library.startsWith('.') || /^[A-Z]:/i.test(library) ? pathToFileURL(resolve(library)).href : library);
  const db = new PGlite();
  try {
    await db.exec(`CREATE ROLE foundit_qa;
      CREATE TYPE item_status AS ENUM('ACTIVE','RESOLVED','CLOSED'); CREATE TYPE item_type AS ENUM('LOST','FOUND');
      CREATE TABLE users(id uuid PRIMARY KEY DEFAULT gen_random_uuid(),name text DEFAULT '',email text DEFAULT '',google_sub text,role text DEFAULT 'user',status text DEFAULT 'active',created_at timestamptz DEFAULT now());
      CREATE TABLE items(id uuid PRIMARY KEY DEFAULT gen_random_uuid(),user_id uuid REFERENCES users(id),type item_type,status item_status,hidden_at timestamptz,latitude numeric,longitude numeric,location_name text DEFAULT '',created_at timestamptz DEFAULT now());
      CREATE TABLE chats(id uuid PRIMARY KEY DEFAULT gen_random_uuid(),item_id uuid,created_at timestamptz DEFAULT now());
      CREATE TABLE user_points(id uuid PRIMARY KEY DEFAULT gen_random_uuid(),user_id uuid UNIQUE REFERENCES users(id),points int DEFAULT 0,updated_at timestamptz DEFAULT now());
      CREATE TABLE point_events(id uuid PRIMARY KEY DEFAULT gen_random_uuid(),user_points_id uuid,type text,points int,description text);
      INSERT INTO users(id,name,role,email) VALUES('00000000-0000-4000-8000-000000000001','Admin','admin','admin@example.test'),('00000000-0000-4000-8000-000000000002','Owner','user','admin@example.test'),('00000000-0000-4000-8000-000000000003','Other','user','other@example.test');
      INSERT INTO items(user_id,type,status,latitude,longitude) VALUES('00000000-0000-4000-8000-000000000002','LOST','ACTIVE',22.998,120.22),('00000000-0000-4000-8000-000000000002','FOUND','ACTIVE',25.03,121.56);
      GRANT SELECT,INSERT,UPDATE ON users,items,user_points,point_events TO foundit_qa;`);
    process.env.DB_USER = 'foundit_qa';
    const query = async (sql, params) => params ? (await db.query(sql, params)).rows : (await db.exec(sql)).at(-1)?.rows || [];
    await new WebInterop1793059200000().up({query});
    await new Campus1793059201000().up({query});
    assert.equal((await query('SELECT count(*)::int AS n FROM users'))[0].n, 3, 'mobile accounts preserved');
    assert.equal((await query("SELECT count(*)::int AS n FROM items WHERE campus_code='ncku'"))[0].n, 1, 'NCKU geofence backfill');
    await db.exec(`INSERT INTO items(location_name,latitude,longitude) VALUES
      ('成大',NULL,NULL),('國立成功大學',NULL,NULL),('成大',25.03,121.56),('成大附近',NULL,NULL),('清華大學',NULL,NULL)`);
    const beforeRepair = await query('SELECT id,user_id,type,status,hidden_at,latitude,longitude,location_name,created_at FROM items ORDER BY id');
    await new LegacyCampus1793059202000().up({query});
    assert.equal((await query("SELECT count(*)::int AS n FROM items WHERE campus_code='ncku'"))[0].n, 3, 'legacy exact NCKU names are included');
    assert.equal((await query("SELECT count(*)::int AS n FROM items WHERE campus_code='ncku' AND latitude=25.03"))[0].n, 0, 'outside coordinates override campus names');
    assert.deepEqual(await query('SELECT id,user_id,type,status,hidden_at,latitude,longitude,location_name,created_at FROM items ORDER BY id'), beforeRepair, 'repair preserves all listing data except campus classification');
    await new LegacyCampus1793059202000().up({query});
    assert.equal((await query("SELECT count(*)::int AS n FROM items WHERE campus_code='ncku'"))[0].n, 3, 'repair is idempotent');
    await db.exec('SET ROLE foundit_qa');
    // Match TypeORM PostgresQueryRunner's UPDATE/DELETE tuple result, not only pg.rows.
    const manager = {query:async(sql,params) => {const result=await db.query(sql,params);return /^\s*(UPDATE|DELETE)\b/i.test(sql)?[result.rows,result.affectedRows]:result.rows;}};
    const source = {transaction:async fn => {await db.exec('BEGIN');try {const result=await fn(manager);await db.exec('COMMIT');return result;}catch(e){await db.exec('ROLLBACK');throw e;}}};
    const service = new CampusService(source);
    const admin={id:'00000000-0000-4000-8000-000000000001',verifiedEmail:'admin@example.test'};
    const owner={id:'00000000-0000-4000-8000-000000000002',verifiedEmail:''};
    const other={id:'00000000-0000-4000-8000-000000000003',verifiedEmail:''};
    assert.equal((await service.call('my_staff',{},admin)).role,'admin');
    assert.equal((await service.call('my_staff',{},owner)).role,null,'editable email cannot grant staff');
    await assert.rejects(()=>service.call('admin_create_sticker_batch',{p_label:'no',p_place:'',p_count:1},owner));
    await assert.rejects(()=>service.call('my_staff',{},null));
    await assert.rejects(()=>service.call('unknown',{},admin));
    await assert.rejects(()=>service.call('my_staff',{sql:'SELECT 1'},admin));
    const station={id:'manual-qa-one',name:'QA counter'};
    await assert.rejects(()=>service.call('station_insert',{station},owner));
    await service.call('station_insert',{station},admin);
    const [row]=await service.call('station_list',{},null);
    assert.equal(row.data.name,station.name);
    assert.equal((await service.call('station_update',{station,stamp:'2000-01-01'},admin)).changed,false,'stale writes rejected');
    assert.equal((await service.call('station_update',{station:{...station,name:'Updated'},stamp:new Date(row.updated_at).toISOString()},admin)).changed,true,'matching stamp updates');
    assert.equal((await service.call('audit_list',{limit:20},admin)).length,2);
    await assert.rejects(()=>service.call('audit_list',{limit:20},owner),'private audit protected');
    const batch=await service.call('admin_create_sticker_batch',{p_label:'QA',p_place:'',p_count:2},admin);
    const codes=await service.call('admin_sticker_codes',{p_batch:batch.batch_id},admin);
    const code=codes[0].code;
    assert.equal((await service.call('sticker_lookup',{p_code:code},null)).status,'unbound');
    await service.call('sticker_bind',{p_code:code,p_item_name:'Bottle'},owner);
    await assert.rejects(()=>service.call('sticker_bind',{p_code:code,p_item_name:'stolen'},other));
    const found=await service.call('sticker_notify',{p_code:code,p_message:'Found it',p_contact:'',p_device:'qa-device'},null);
    await assert.rejects(()=>service.call('sticker_thread_finder',{p_thread:found.thread_id,p_token:'wrong'},null));
    await assert.rejects(()=>service.call('sticker_thread_owner',{p_thread:found.thread_id},other));
    assert.equal((await service.call('sticker_thread_owner',{p_thread:found.thread_id},owner)).messages[0].body,'Found it');
    await service.call('sticker_reply_owner',{p_thread:found.thread_id,p_body:'Thank you'},owner);
    assert.equal((await service.call('sticker_thread_finder',{p_thread:found.thread_id,p_token:found.token},null)).messages.length,2);
    await service.call('sticker_unbind',{p_code:code},owner);
    await service.call('sticker_bind',{p_code:code,p_item_name:'New owner'},other);
    await assert.rejects(()=>service.call('sticker_thread_owner',{p_thread:found.thread_id},other),'rebinding never transfers old chats');
    assert.equal((await service.call('public_counters',{},null)).members,0,'fresh Web member count');
    await service.call('admin_kpis',{p_days:null},admin);
    const points = new PointsService({manager:source},{});
    assert.equal(await points.award(owner.id,'daily_login','2026-10-27','Daily'),true);
    assert.equal(await points.award(owner.id,'daily_login','2026-10-27','Daily'),false);
    for(let i=0;i<7;i++)assert.equal(await points.award(owner.id,'qr_scan','tag'+i,'Scan'),i<5);
    const [total]=await query('SELECT points FROM user_points WHERE user_id=$1',[owner.id]);assert.equal(total.points,105);
    await assert.rejects(()=>service.withUser(other,m=>m.query('SELECT campus.erase_member($1)',[owner.id])),'cannot erase another account');
    await service.withUser(owner,m=>m.query('SELECT campus.erase_member($1)',[owner.id]));
    await assert.rejects(()=>service.call('sticker_thread_owner',{p_thread:found.thread_id},owner),'deleted account cannot recover old private thread');
    console.log('PASS: migrations, preservation, campus scope, RLS, identity, station conflicts, sticker ownership, private threads and idempotent points');
  } finally { await db.close(); }
}
main().catch(error=>{console.error(error.message);process.exitCode=1;});
